  // ═══════════════════════════════════════════════════════════════════════════
  // Convenience Getters
  // ═══════════════════════════════════════════════════════════════════════════

  /// Whether this application is for an invitation flow.
  bool get isInvitation => source == StaffApplicationSource.invitation;

  /// Whether this application is for a self-registration flow.
  bool get isSelfRegistration =>
      source == StaffApplicationSource.selfRegistration;

  /// Whether this application has been archived (soft deleted).
  bool get isArchived => archivedAt != null;

  /// Whether this application has been reviewed (approved or rejected).
  bool get hasBeenReviewed =>
      status == StaffApprovalStatus.approved ||
      status == StaffApprovalStatus.rejected;

  /// Whether this is a reapplication (has a previous application).
  bool get isReapplication => previousApplicationId != null;

  /// Whether this application has scope assignments set.
  bool get hasScopeAssignment =>
      assignedCampusIds.isNotEmpty ||
      assignedStageIds.isNotEmpty ||
      assignedClassIds.isNotEmpty ||
      assignedSubjectIds.isNotEmpty;

  /// Whether the invitation has expired.
  bool get isInvitationExpired =>
      status == StaffApprovalStatus.invited &&
      expiresAt != null &&
      expiresAt!.isBefore(DateTime.now());

  // ═══════════════════════════════════════════════════════════════════════════
  // Helpers
  // ═══════════════════════════════════════════════════════════════════════════

  /// Convert a Firestore Timestamp to DateTime, returning null if null.
  static DateTime? _timestampToDateTime(Timestamp? timestamp) {
    return timestamp?.toDate();
  }

  @override
  String toString() =>
      'StaffApplication(id: $id, email: $email, status: ${status.value}, '
      'staffType: ${staffType.value}, orgId: $organizationId, version: $version)';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is StaffApplication &&
          runtimeType == other.runtimeType &&
          id == other.id &&
          version == other.version &&
          status == other.status;

  @override
  int get hashCode => id.hashCode ^ version.hashCode ^ status.hashCode;
