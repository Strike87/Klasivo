// ═══════════════════════════════════════════════════════════════════════════════
// KLASIVO — Staff Application Model
//
// Mirrors the `staff_applications` Firestore collection.
// Each document represents a staff onboarding application with full
// lifecycle tracking: identity, approval state machine, scope assignment,
// review trail, and archival support.
//
// Key design decisions:
//   - Source of truth for approval status (NOT mirrored on users doc)
//   - Users doc only stores `applicationId` pointer
//   - All state transitions enforced server-side via Firestore transactions
//   - Version field provides idempotency protection against double-clicks
//   - invitedEmailNormalized prevents case-sensitivity invitation bugs
//   - previousApplicationId links reapplication chains
//   - archivedAt/archivedBy enable soft deletion for long-term data hygiene
// ═══════════════════════════════════════════════════════════════════════════════

import 'package:cloud_firestore/cloud_firestore.dart';

import 'staff_approval_status.dart';
import 'staff_type.dart';

/// The source of the staff application.
///
/// - [selfRegistration]: The staff member registered themselves.
/// - [invitation]: An owner/admin invited the staff member.
enum StaffApplicationSource {
  selfRegistration('self_registration'),
  invitation('invitation');

  const StaffApplicationSource(this.value);

  final String value;

  static StaffApplicationSource fromString(String? value) {
    return StaffApplicationSource.values.firstWhere(
      (e) => e.value == value,
      orElse: () => StaffApplicationSource.selfRegistration,
    );
  }
}

/// A staff onboarding application.
///
/// This is the central document for the staff approval workflow.
/// It tracks the full lifecycle from application through approval,
/// rejection, revocation, and archival.
///
/// Firestore collection: `staff_applications`
class StaffApplication {
  // ─── Identity ──────────────────────────────────────────────────────────────

  /// Document ID (auto-generated by Firestore).
  final String id;

  /// Firebase Auth UID of the applicant.
  /// Null until the teacher registers or accepts an invitation.
  final String? userId;

  /// Applicant's email address (as entered or provided by inviter).
  final String email;

  /// Applicant's email in lowercase, for case-insensitive matching.
  /// Example: 'Teacher@School.com' → 'teacher@school.com'
  final String invitedEmailNormalized;

  /// Applicant's display name.
  final String? fullName;

  /// Applicant's phone number.
  final String? phoneNumber;

  /// Applicant's profile photo URL.
  final String? photoUrl;

  // ─── Organization ──────────────────────────────────────────────────────────

  /// The organization this application belongs to.
  final String organizationId;

  // ─── Staff Type ────────────────────────────────────────────────────────────

  /// The type of staff being onboarded (teacher, assistant_teacher, counselor).
  final StaffType staffType;

  // ─── Approval State Machine ────────────────────────────────────────────────

  /// Current approval status.
  final StaffApprovalStatus status;

  /// How this application was initiated.
  final StaffApplicationSource source;

  // ─── Invitation-Specific (Flow C) ──────────────────────────────────────────

  /// Reference to the invite_codes document (if invitation flow).
  final String? inviteCodeId;

  /// UID of the owner/admin who sent the invitation.
  /// Resolve name from users collection, do NOT store name here.
  final String? invitedBy;

  /// When the invitation was sent.
  final DateTime? invitedAt;

  /// When the invitation expires.
  final DateTime? expiresAt;

  // ─── Review ────────────────────────────────────────────────────────────────

  /// UID of the owner/admin who reviewed this application.
  /// Resolve name from users collection, do NOT store name here.
  final String? reviewedBy;

  /// When the application was reviewed.
  final DateTime? reviewedAt;

  /// General notes left by the reviewer for any action (approve, reject, etc.).
  /// Examples: 'Approved after credential review', 'Missing teaching certification'.
  final String? reviewNotes;

  // ─── Revocation ────────────────────────────────────────────────────────────

  /// UID of the owner/admin who revoked access.
  final String? revokedBy;

  /// When the access was revoked.
  final DateTime? revokedAt;

  // ─── Reapplication Chain ───────────────────────────────────────────────────

  /// Reference to the previous application if this is a reapplication.
  /// Enables history chain: Application A (rejected) → Application B (approved).
  final String? previousApplicationId;

  // ─── Scope Assignment (set on approval) ────────────────────────────────────

  /// The RBAC role assigned upon approval.
  /// Defaults to staffType.defaultRole but can be overridden by reviewer.
  final String assignedRole;

  /// Campus IDs assigned to this staff member.
  final List<String> assignedCampusIds;

  /// Stage IDs assigned to this staff member.
  final List<String> assignedStageIds;

  /// Class IDs assigned to this staff member.
  final List<String> assignedClassIds;

  /// Subject IDs assigned to this staff member.
  final List<String> assignedSubjectIds;

  // ─── Metadata ──────────────────────────────────────────────────────────────

  /// Optional note from the applicant explaining their application.
  final String? applicationNote;

  /// Credentials, subjects, or qualifications claimed by the applicant.
  final String? qualifications;

  // ─── Soft Deletion / Archival ──────────────────────────────────────────────

  /// When this application was archived (soft delete).
  /// Archived applications remain in Firestore for audit history
  /// but are excluded from active queries.
  final DateTime? archivedAt;

  /// UID of the user who archived this application.
  final String? archivedBy;

  // ─── Idempotency Protection ────────────────────────────────────────────────

  /// Monotonically increasing version number.
  /// Incremented on every state transition within a Firestore transaction.
  /// Prevents double-click race conditions:
  ///   - Owner clicks Approve twice
  ///   - Two Cloud Function executions race
  ///   - Transaction checks version == expectedVersion before updating
  ///   - Second execution sees version mismatch → rejects
  final int version;

  // ─── Timestamps ────────────────────────────────────────────────────────────

  /// When this application was created.
  final DateTime? createdAt;

  /// When this application was last updated.
  final DateTime? updatedAt;

  // ═══════════════════════════════════════════════════════════════════════════
  // Constructor
  // ═══════════════════════════════════════════════════════════════════════════

  const StaffApplication({
    required this.id,
    this.userId,
    required this.email,
    required this.invitedEmailNormalized,
    this.fullName,
    this.phoneNumber,
    this.photoUrl,
    required this.organizationId,
    required this.staffType,
    required this.status,
    required this.source,
    this.inviteCodeId,
    this.invitedBy,
    this.invitedAt,
    this.expiresAt,
    this.reviewedBy,
    this.reviewedAt,
    this.reviewNotes,
    this.revokedBy,
    this.revokedAt,
    this.previousApplicationId,
    this.assignedRole = 'teacher',
    this.assignedCampusIds = const [],
    this.assignedStageIds = const [],
    this.assignedClassIds = const [],
    this.assignedSubjectIds = const [],
    this.applicationNote,
    this.qualifications,
    this.archivedAt,
    this.archivedBy,
    this.version = 1,
    this.createdAt,
    this.updatedAt,
  });

